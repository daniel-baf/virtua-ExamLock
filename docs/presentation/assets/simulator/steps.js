export const STEP_START_TIME = new Date(2026, 4, 20, 8, 0, 0);

// Acumula cuánto sim-time hay antes de cada step
export function getStepStartSimTime(stepIdx) {
    let t = STEP_START_TIME.getTime();
    for (let i = 0; i < stepIdx; i++) t += STEPS[i].simDeltaMs;
    return new Date(t);
}
